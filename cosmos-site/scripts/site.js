import { authority, canonicalUrl } from '../src/site/authority.js';
import product, { productResourceUrl, productRouteUrl } from '../src/site/product.js';

export const esc = (value) =>
  String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const xml = (value) => esc(value).replaceAll("'", '&apos;');

export const sitePaths = [
  '404.html',
  authority.discovery.robots.slice(1),
  authority.discovery.sitemap.slice(1),
  authority.feed.slice(1),
  '.well-known/security.txt',
  '_redirects',
  authority.discovery.llms.slice(1),
  authority.discovery.fullText.slice(1),
  'humans.txt',
  '_headers',
  authority.discovery.ard.slice(1),
  authority.discovery.legacyCatalog.slice(1),
];

export function siteOutputs({ agentEntries = [], documents = new Map() } = {}) {
  const catalog = agentCatalog(agentEntries);
  return new Map([
    ['404.html', notFoundHtml()],
    [authority.discovery.robots.slice(1), robotsTxt()],
    [authority.discovery.sitemap.slice(1), sitemapXml()],
    [authority.feed.slice(1), releasesXml()],
    ['.well-known/security.txt', securityTxt()],
    ['_redirects', redirects()],
    [authority.discovery.llms.slice(1), llmsTxt()],
    [authority.discovery.fullText.slice(1), llmsFullTxt(documents)],
    ['humans.txt', humansTxt()],
    ['_headers', headers()],
    [authority.discovery.ard.slice(1), catalog],
    [authority.discovery.legacyCatalog.slice(1), catalog],
  ]);
}

function notFoundHtml() {
  return `<!DOCTYPE html>
<!-- Generated by scripts/site.js. -->
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="dark light"><title>Not found | ${esc(authority.name)}</title><meta name="robots" content="noindex, nofollow"><link rel="icon" href="/favicon.ico"><style>body{margin:0;background:#120A14;color:#FFECE2;font:16px/1.6 system-ui,sans-serif}main{max-width:34rem;margin:0 auto;padding:12vh 1.5rem}h1{font-size:1.6rem}a{color:#FFB37A}</style></head><body><main><p>404</p><h1>That page is not on this origin.</h1><p><a href="/">Open the Cosmos Design System</a></p></main></body></html>
`;
}

function robotsTxt() {
  return `User-agent: *
Allow: /

Sitemap: ${canonicalUrl(authority.discovery.sitemap)}
Agentmap: ${canonicalUrl(authority.discovery.ard)}
`;
}

function sitemapXml() {
  const entries = product.routes.filter((route) => route.inSitemap);
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.map((route) => `  <url><loc>${xml(productRouteUrl(route))}</loc><lastmod>${product.updated}</lastmod><changefreq>monthly</changefreq></url>`).join('\n')}
</urlset>
`;
}

function securityTxt() {
  return `Contact: ${authority.security.contact}
Expires: ${authority.security.expires}
Canonical: ${canonicalUrl('/.well-known/security.txt')}
Preferred-Languages: en
`;
}

function redirects() {
  return [
    `# ${authority.name} rewrites`,
    '# Generated by scripts/site.js — do not edit by hand.',
    '# Clean routes are 200 rewrites; the legacy local prefix is a same-host 301.',
    '',
    ...product.rewrites(),
    ...product.redirects(),
    '',
  ].join('\n');
}

function llmsTxt() {
  return `# ${authority.name}

> ${authority.tagline}
> ${authority.description}

${product.llms()}

## Agent discovery

- [Full text](${canonicalUrl(authority.discovery.fullText)}): the complete specification and agent brief in one document.
- [Release feed](${canonicalUrl(authority.feed)}): Atom release history.
- [Resource catalog](${canonicalUrl(authority.discovery.ard)}): machine-readable discovery entries.
- [Parent reference](${authority.parent}): the SIMT reference context that points to this authority.
`;
}

function llmsFullTxt(documents) {
  const references = product.fullTextResources.map((path) => {
    if (!product.resources.some((resource) => resource.path === path)) throw new Error(`Undeclared full-text resource: ${path}`);
    const text = documents.get(path);
    if (!text) throw new Error(`Missing full-text resource: ${path}`);
    const source = productResourceUrl({ path });
    const resolved = text.replace(/\]\(([^\s)]+)\)/g, (_, href) => `](${new URL(href, source).href})`);
    return `Source: ${source}\n\n${resolved}`;
  });
  return `# ${authority.name} — full text

> ${authority.tagline}
> ${authority.description}

${product.llms()}

## Full references

${references.join('\n\n---\n\n')}
`;
}

